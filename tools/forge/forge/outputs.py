"""The committed, generated outputs of ``forge build`` (ASSET_PIPELINE §9.3, CLAUDE.md §6.1).

Paths are relative to the output root: the repo root for a normal build, or ``--out <dir>``
(which is what ``forge verify`` rebuilds into, so the two trees compare path for path):

- ``public/assets/atlas/<name>.png`` and ``<name>.json`` for every atlas with frames
  (:mod:`forge.pack`); ``public/assets/atlas/`` is owned by the forge, so anything else in it
  is removed;
- ``src/gen/assets.ts``: the typed ``FRAME`` table, ``FrameId`` and ``AssetId``;
- ``public/assets/asset-hashes.json``: every file above mapped to its SHA-256, sorted by key.

Everything is a pure function of the packed atlases and the manifest IDs: no clock, no
absolute paths, sorted keys, ``\\n`` line endings.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from pathlib import Path

from forge.pack import Atlas, atlas_json, atlas_png
from forge.palette import Palette
from forge.pngio import write_bytes_if_changed

__all__ = [
    "ASSETS_TS",
    "ASSETS_TS_HEADER",
    "ATLAS_DIR",
    "HASHES_JSON",
    "asset_hashes_json",
    "assets_ts",
    "generated_files",
    "sha256_hex",
    "write_outputs",
]

ATLAS_DIR = "public/assets/atlas"
ASSETS_TS = "src/gen/assets.ts"
HASHES_JSON = "public/assets/asset-hashes.json"

ASSETS_TS_HEADER = "// GENERATED by forge build. Do not edit. Source: assets-src/manifest.json"
"""First line of ``src/gen/assets.ts`` (the ASSET_PIPELINE §9.3 wording)."""


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _ts_string(s: str) -> str:
    # JSON string syntax is valid TypeScript string syntax.
    return json.dumps(s, ensure_ascii=False)


def assets_ts(atlases: Sequence[Atlas], asset_ids: Sequence[str]) -> bytes:
    """``src/gen/assets.ts``: ``FRAME`` (sorted by frame id), ``FrameId`` and ``AssetId``.

    ``asset_ids`` is every manifest ID (the ``AssetId`` union); ``FRAME`` holds every packed
    frame with its atlas name, rect and pivot.
    """
    rows = sorted(((af.frame_id, a.name, af) for a in atlases for af in a.frames), key=lambda r: r[0])
    ids = [r[0] for r in rows]
    if len(set(ids)) != len(ids):
        raise ValueError("a frame id appears in more than one atlas")
    lines = [ASSETS_TS_HEADER]
    if rows:
        lines.append("export const FRAME = {")
        for fid, name, af in rows:
            lines.append(
                f"  {_ts_string(fid)}: {{ atlas: {_ts_string(name)}, x: {af.x}, y: {af.y}, w: {af.w}, h: {af.h}, "
                f"px: {af.px}, py: {af.py} }},"
            )
        lines.append("} as const;")
    else:
        lines.append("export const FRAME = {} as const;")
    lines.append("export type FrameId = keyof typeof FRAME;")
    uniq = sorted(set(asset_ids))
    union = " | ".join(_ts_string(i) for i in uniq) if uniq else "never"
    lines.append(f"export type AssetId = {union};")
    return ("\n".join(lines) + "\n").encode("utf-8")


def asset_hashes_json(files: Mapping[str, bytes]) -> bytes:
    """``public/assets/asset-hashes.json``: ``{ "<repo-relative path>": "<sha256 hex>" }``, sorted by key."""
    doc = {path: sha256_hex(files[path]) for path in sorted(files)}
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def generated_files(atlases: Sequence[Atlas], asset_ids: Sequence[str], palette: Palette) -> dict[str, bytes]:
    """Every generated output, keyed by its path relative to the output root, sorted by path."""
    files: dict[str, bytes] = {}
    for a in atlases:
        files[f"{ATLAS_DIR}/{a.name}.png"] = atlas_png(a, palette)
        files[f"{ATLAS_DIR}/{a.name}.json"] = atlas_json(a)
    files[ASSETS_TS] = assets_ts(atlases, asset_ids)
    files[HASHES_JSON] = asset_hashes_json(files)
    return dict(sorted(files.items()))


def write_outputs(root: Path, files: Mapping[str, bytes]) -> list[str]:
    """Write ``files`` under ``root`` and remove stale files from ``root/public/assets/atlas/``.

    Returns the paths (relative to ``root``) whose bytes changed. Unchanged files are not
    rewritten, so their mtimes stay put.
    """
    atlas_dir = root / ATLAS_DIR
    if atlas_dir.is_dir():
        keep = {Path(p).name for p in files if p.startswith(f"{ATLAS_DIR}/")}
        for stale in sorted(atlas_dir.iterdir()):
            if stale.name not in keep and stale.is_file():
                stale.unlink()
    changed: list[str] = []
    for rel, data in files.items():
        if write_bytes_if_changed(root / rel, data):
            changed.append(rel)
    return changed
