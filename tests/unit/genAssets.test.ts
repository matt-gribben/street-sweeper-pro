// The generated asset table (SSP-010; ASSET_PIPELINE §9.3, TECHNICAL_DESIGN §2 rule 5).
// src/gen/assets.ts is written only by `npm run assets`; this test pins its contract: the header, 232 frame
// IDs (205 from M0: Bessie, her brush, the SSP-014 spike pedestrian, the SSP-020 lamp post slices and the SSP-024
// litter sample; 27 from SSP-041: the Puddle Lane facade sets and roof surfaces in the world atlas), a FrameId
// union that rejects unknown frames at compile time, and agreement with the atlas JSON.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { type AssetId, FRAME, type FrameId } from '../../src/gen/assets.ts';

const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));

function readRepoFile(relPath: string): string {
  return readFileSync(`${REPO_ROOT}${relPath}`, 'utf8');
}

interface AtlasRect {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
  readonly px: number;
  readonly py: number;
}

function isAtlasRect(value: unknown): value is AtlasRect {
  if (typeof value !== 'object' || value === null) return false;
  return ['x', 'y', 'w', 'h', 'px', 'py'].every((k) =>
    Number.isInteger((value as Record<string, unknown>)[k]),
  );
}

function loadAtlasFrames(name: string): Record<string, AtlasRect> {
  const parsed: unknown = JSON.parse(readRepoFile(`public/assets/atlas/${name}.json`));
  if (typeof parsed !== 'object' || parsed === null || !('frames' in parsed) || !('swaps' in parsed)) {
    throw new Error(`atlas ${name}.json must be { frames, swaps }`);
  }
  const frames: unknown = parsed.frames;
  if (typeof frames !== 'object' || frames === null)
    throw new Error(`atlas ${name}.json: frames is not an object`);
  const out: Record<string, AtlasRect> = {};
  for (const [id, rect] of Object.entries(frames)) {
    if (!isAtlasRect(rect)) throw new Error(`atlas ${name}.json: bad rect for ${id}`);
    out[id] = rect;
  }
  return out;
}

describe('src/gen/assets.ts', () => {
  it('starts with the ASSET_PIPELINE §9.3 header', () => {
    const firstLine = readRepoFile('src/gen/assets.ts').split('\n')[0];
    expect(firstLine).toBe('// GENERATED by forge build. Do not edit. Source: assets-src/manifest.json');
  });

  it('holds exactly 232 frame IDs: 18 facade, 9 roof, 1 litter.banana_skin, 8 npc.old_woman, 4 prop.lamp_post, 64 veh.sweeper, 128 veh.sweeper_brush', () => {
    const ids = Object.keys(FRAME);
    expect(ids).toHaveLength(232);
    expect(ids.filter((id) => id.startsWith('facade.'))).toHaveLength(18);
    expect(ids.filter((id) => id.startsWith('roof.'))).toHaveLength(9);
    expect(ids.filter((id) => id.startsWith('litter.banana_skin:'))).toEqual([
      'litter.banana_skin:idle:h00:0',
    ]);
    expect(ids.filter((id) => id.startsWith('npc.old_woman:'))).toHaveLength(8);
    expect(ids.filter((id) => id.startsWith('prop.lamp_post:'))).toHaveLength(4);
    expect(ids.filter((id) => id.startsWith('veh.sweeper:'))).toHaveLength(64);
    expect(ids.filter((id) => id.startsWith('veh.sweeper_brush:'))).toHaveLength(128);
    expect(ids).toEqual([...ids].sort());
  });

  it('types a known frame and rejects an unknown one at compile time', () => {
    const h07 = FRAME['veh.sweeper:body:h07:0'];
    expect(h07.atlas).toBe('actors');
    expect([h07.w, h07.h, h07.px, h07.py]).toEqual([64, 64, 32, 32]);
    const brush: FrameId = 'veh.sweeper_brush:brush:h31:3';
    expect(FRAME[brush].w).toBe(96);
    const doris: FrameId = 'npc.old_woman:idle:s:0';
    expect([FRAME[doris].w, FRAME[doris].h]).toEqual([24, 24]);

    // @ts-expect-error h99 is not a heading, so it is not a FrameId (a missing sprite is a compile error).
    const missing = FRAME['veh.sweeper:body:h99:0'];
    expect(missing).toBeUndefined();
    // @ts-expect-error the same check through the FrameId union.
    const notAFrame: FrameId = 'veh.sweeper:body:h99:0';
    expect(notAFrame in FRAME).toBe(false);
  });

  it('types the SSP-041 facade bays (lit/base/dark, 64x80) and roof variants (32x32) in the world atlas', () => {
    for (const state of ['lit', 'base', 'dark'] as const) {
      const bay = FRAME[`facade.terrace_brick:${state}:-:0`];
      expect([bay.atlas, bay.w, bay.h]).toEqual(['world', 64, 80]);
    }
    const slate: FrameId = 'roof.slate:v:-:3';
    expect([FRAME[slate].atlas, FRAME[slate].w, FRAME[slate].h]).toEqual(['world', 32, 32]);
    expect(FRAME['roof.depot:v:-:0'].atlas).toBe('world');
    // @ts-expect-error facade modules are source grids, not manifest assets, so they have no frames.
    const module: FrameId = 'facade.window_sash:base:-:0';
    expect(module in FRAME).toBe(false);
  });

  it('exposes the manifest asset IDs as AssetId', () => {
    const ids: AssetId[] = [
      'facade.corner_shop',
      'facade.depot_shed',
      'facade.flats_render',
      'facade.parade_brick',
      'facade.terrace_brick',
      'facade.terrace_brick_bay',
      'litter.banana_skin',
      'npc.old_woman',
      'prop.lamp_post',
      'roof.depot',
      'roof.felt',
      'roof.slate',
      'veh.sweeper',
      'veh.sweeper_brush',
    ];
    // @ts-expect-error not a manifest asset ID.
    const unknown: AssetId = 'veh.tractor';
    expect(ids).not.toContain(unknown);
    const manifest: unknown = JSON.parse(readRepoFile('assets-src/manifest.json'));
    const manifestIds = (manifest as { assets: { id: string }[] }).assets.map((a) => a.id).sort();
    expect(manifestIds).toEqual(ids);
  });

  it('agrees with the atlas JSON rects and pivots', () => {
    const atlases = new Map<string, Record<string, AtlasRect>>();
    for (const [id, frame] of Object.entries(FRAME)) {
      let rects = atlases.get(frame.atlas);
      if (rects === undefined) {
        rects = loadAtlasFrames(frame.atlas);
        atlases.set(frame.atlas, rects);
      }
      const rect = rects[id];
      expect(rect, id).toBeDefined();
      expect({ x: frame.x, y: frame.y, w: frame.w, h: frame.h, px: frame.px, py: frame.py }).toEqual(rect);
    }
    const atlasFrameCount = [...atlases.values()].reduce((n, rects) => n + Object.keys(rects).length, 0);
    expect(atlasFrameCount).toBe(Object.keys(FRAME).length);
  });

  it('lists every generated file in asset-hashes.json, sorted by key', () => {
    const parsed: unknown = JSON.parse(readRepoFile('public/assets/asset-hashes.json'));
    const keys = Object.keys(parsed as Record<string, string>);
    expect(keys).toEqual([...keys].sort());
    expect(keys).toEqual([
      'public/assets/atlas/actors.json',
      'public/assets/atlas/actors.png',
      'public/assets/atlas/items.json',
      'public/assets/atlas/items.png',
      'public/assets/atlas/world.json',
      'public/assets/atlas/world.png',
      // Listed by the level compiler after forge build (SSP-042).
      'public/assets/levels/puddle_lane.json',
      'src/gen/assets.ts',
    ]);
    for (const hash of Object.values(parsed as Record<string, string>))
      expect(hash).toMatch(/^[0-9a-f]{64}$/);
  });
});
