// The generated asset table (SSP-010; ASSET_PIPELINE §9.3, TECHNICAL_DESIGN §2 rule 5).
// src/gen/assets.ts is written only by `npm run assets`; this test pins its contract: the header, 732 frame
// IDs (204 from M0: Bessie, her brush, the SSP-014 spike pedestrian and the SSP-020 lamp post slices; 27 from
// SSP-041: the Puddle Lane facade sets and roof surfaces in the world atlas; 85 from SSP-040: the ground tiles,
// the 47-tile kerb blob and haz.speed_bump; 180 from SSP-051: the 15 litter IDs, idle x1 + wobble x2 in the
// four code-generated rotations h00/h08/h16/h24, in the items atlas; 200 from SSP-068: the Kerbside 5x7 glyph
// and outline frames in the ui atlas; 33 from SSP-052: 12 stain and 12 grime overlay variants in the world
// atlas, 3 pickups x 2 bob frames, the flat hydrant, depot bay and skip placeholders in the items atlas; 3 from
// SSP-285: the placeholder 9-slice panels ui.panel_council/_paper/_dark in the ui atlas), a
